a = 9
b = 2

#operadores numericos basicos
print("Suma: ", a + b)
print("Resta: ", a - b)
print("Multiplicación: ", a * b)
print("División: ", a / b)

#otros operadores numericos
print("División: ", a % b)
print("Parte entera de la división: ", a // b)
print("Potenciación: ", a ** b)

#shortcuts
a += 2
print(a)

#pemdas
operation1 = 2 + 5 * 3
operation2 = (2 + 5) * 3

print(operation1)
print(operation2)

operation3 = (2+6) * (5**3) / 8 - 2
print(operation3)